def test_wire_codec_does_not_claim_charge_or_discharge_direction(codec: Any) -> None:
    """T-UNIT-PROTO-012 / UNC-POWER-SIGN / S0: signed P is not a verified direction."""
    parameter_names = tuple(inspect.signature(codec.encode_pq_registers).parameters)

    assert parameter_names == ("active_w", "reactive_var")
    assert "charge" not in parameter_names
    assert "discharge" not in parameter_names
