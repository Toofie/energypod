@pytest.mark.parametrize("raw", [-1, 65536, True, False, 1.5, "65535", None])
def test_signed_register_decoder_rejects_non_register_values(codec: Any, raw: Any) -> None:
    """T-UNIT-PROTO-004 / INV-RANGE-002 / S1."""
    with pytest.raises(codec.ProtocolValueError):
        codec.decode_signed16(raw)


def test_signed_register_round_trip_covers_all_ushort_bit_patterns(codec: Any) -> None:
    """T-UNIT-PROTO-005 / INV-RANGE-001 / S0: int16 conversion is exhaustive."""
    for raw in range(0x1_0000):
        assert codec.encode_signed16(codec.decode_signed16(raw)) == raw


@pytest.mark.parametrize(
    ("field_name", "words", "expected"),
    [
        # GetUintFromUshort(high, low) == (high << 16) | low.
        ("SYSTEM_HISTORY", (0x1234, 0x5678), 0x12345678),
        ("LEGACY_PCS_ENERGY", (0x1234, 0x5678), 0x12345678 * 0.1),
        ("LEGACY_BMS_ENERGY", (0x1234, 0x5678), 0x12345678 * 0.1),
        ("LEGACY_BECU_ENERGY", (0x1234, 0x5678), 0x12345678 * 0.001),
        ("LEGACY_BECU_CAPACITY", (0x1234, 0x5678), 0x12345678),
        # For the same lower-address-first input pair, these call sites reverse the helper args.
        ("IOT_BMS_ENERGY", (0x1234, 0x5678), 0x56781234 * 0.1),
        ("IOT_TOTAL_ENERGY", (0x1234, 0x5678), 0x56781234 * 0.1),
        ("RTU_ID", (0x1234, 0x5678), 0x56781234),
    ],
)
def test_field_specific_u32_reference_vectors(
    codec: Any,
    field_name: str,
    words: tuple[int, int],
    expected: int | float,
) -> None:
    """T-UNIT-PROTO-006 / V-SYS,V-IOT,V-LEGACY,V-LAYOUT / S0."""
    field = getattr(codec.UInt32Field, field_name)
    assert codec.decode_uint32(field, words) == pytest.approx(expected)


def test_u32_field_metadata_forbids_a_universal_word_order(codec: Any) -> None:
    """T-UNIT-PROTO-007 / INV-ENDIAN-001 / S0: every field family is explicit."""
    high_first = {
        "SYSTEM_HISTORY",
        "LEGACY_PCS_ENERGY",
        "LEGACY_BMS_ENERGY",
        "LEGACY_BECU_ENERGY",
        "LEGACY_BECU_CAPACITY",
    }
    low_first = {"IOT_BMS_ENERGY", "IOT_TOTAL_ENERGY", "RTU_ID"}

    for name in high_first:
        spec = codec.UINT32_CODECS[getattr(codec.UInt32Field, name)]
        assert spec.word_order is codec.WordOrder.HIGH_WORD_FIRST
    for name in low_first:
        spec = codec.UINT32_CODECS[getattr(codec.UInt32Field, name)]
        assert spec.word_order is codec.WordOrder.LOW_WORD_FIRST

    system_history = codec.UINT32_CODECS[codec.UInt32Field.SYSTEM_HISTORY]
    assert float(system_history.scale) == 1.0
    assert system_history.engineering_unit is None


